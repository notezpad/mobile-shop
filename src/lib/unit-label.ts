/** تنضيف اسم الوحدة اللي المستخدم كتبه: مسافات + حد أقصى للطول. فاضي = null (يعني قطعة). */
export function cleanUnitLabel(raw: unknown): string | null {
  if (raw == null) return null
  const s = String(raw).replace(/\s+/g, ' ').trim().slice(0, 20)
  if (!s || s === DEFAULT_UNIT_LABEL) return null
  return s
}

/** الاسم اللي يتعرض فعلاً (null → قطعة) */
export function unitOf(label: string | null | undefined): string {
  return label && label.trim() ? label.trim() : DEFAULT_UNIT_LABEL
}

function pluralOf(label: string, kind: 0 | 1 | 2): string {
  const known = FORMS[label]
  if (known) return known[kind]
  // اسم مكتوب من المستخدم ومش في القاموس: نسيبه زي ما هو
  return label
}

/**
 * عدد + وحدة بقواعد العربي:
 *  1 → «علبة»، 2 → «علبتين»، 3-10 → «علب»، 11+ → «علبة»، الكسور → مفرد.
 * رقم 1 و2 بنكتبهم بالأرقام برضه («1 علبة») عشان يتقري بسرعة في الكاشير.
 */
export function formatQtyUnit(qty: number, label: string | null | undefined): string {
  const l = unitOf(label)
  const n = Math.round(qty * 1000) / 1000
  return `${n} ${unitWord(n, l)}`
}

/** كلمة الوحدة بس (من غير الرقم) حسب العدد */
export function unitWord(qty: number, label: string | null | undefined): string {
  const l = unitOf(label)
  if (!Number.isInteger(qty)) return pluralOf(l, 0)
  if (qty === 2) return pluralOf(l, 1)
  if (qty >= 3 && qty <= 10) return pluralOf(l, 2)
  return pluralOf(l, 0)
}

/**
 * لو كل الأصناف ليها نفس الوحدة (كلها علب مثلاً) نرجّعها، غير كده «قطعة».
 * بنستخدمها في إجماليات السلة والفواتير اللي فيها أصناف مختلفة.
 */
export function commonUnit(labels: Array<string | null | undefined>): string | null {
  if (labels.length === 0) return null
  const first = unitOf(labels[0])
  for (const l of labels) if (unitOf(l) !== first) return null
  return first === DEFAULT_UNIT_LABEL ? null : first
}

