function matchesRule(norm: string, tokens: string[], kw: string): boolean {
  if (kw.includes(' ')) return (' ' + norm + ' ').includes(' ' + kw + ' ')
  return tokens.some((t) => {
    const bare = t.startsWith('ال') && t.length > 3 ? t.slice(2) : t
    if (bare === kw || t === kw) return true
    // «مكرونة» ↔ «مكرونات» / «بسكويتات» … نقبل لو الكلمة أطول بحرفين تلاتة بحد أقصى
    return kw.length >= 4 && bare.startsWith(kw) && bare.length - kw.length <= 3
  })
}

/**
 * يخمّن اسم الوحدة من اسم المنتج. بيرجّع null لو مفيش تخمين واضح (يعني «قطعة»).
 *   رز مصري 1 كيلو → كيس | زبادي طبيعي → علبة | مربى فراولة → برطمان | زيت عباد → زجاجة
 */
export function guessUnitLabel(productName: string): string | null {
  const norm = normalize(productName || '')
  if (!norm) return null
  const tokens = norm.split(' ')

  for (const [kws, label] of EXPLICIT) {
    if (kws.some((kw) => matchesRule(norm, tokens, normalize(kw)))) return label
  }
  for (const [kws, label] of RULES) {
    if (kws.some((kw) => matchesRule(norm, tokens, normalize(kw)))) return label
  }
  return null
}
