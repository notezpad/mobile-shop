/**
 * ═══════════════════════════════════════════════════════════════════
 * Tracking Layer — Sanitize Platform IDs
 * ═══════════════════════════════════════════════════════════════════
 * عند نسخ معرفات المنصات (G-… / AW-… / GTM-… / Pixel IDs) من صفحات
 * Google / Meta / TikTok — خصوصاً داخل بيئة عربية RTL — تتسرب أحياناً
 * محارف خفية غير مرئية إلى الحقل:
 *   - علامات الاتجاه: RLM (U+200F) / LRM (U+200E)
 *   - Zero-width: ZWNJ (U+200C) / ZWSP (U+200B) / ZWJ (U+200D) / BOM (U+FEFF)
 *   - شرطات شبيهة بالشرطة العادية: – — − ﹣ － ‐ ‑
 *
 * النتيجة قبل هذا المنظّف: تحقق الصيغة يفشل رغم أن المعرف صحيح بصرياً،
 * والأخطر — القيمة الفاسدة تُحفظ وتُحقن في روابط gtag/pixel فيتوقف
 * التتبع بصمت دون أي خطأ ظاهر.
 *
 * هذا الملف shared (بدون أي اعتماديات سيرفر) — يُستخدم في:
 *   - الواجهة: تنظيف فوري أثناء الكتابة/اللصق
 *   - السيرفر: تنظيف قبل التحقق وقبل الحفظ (حماية مزدوجة تُصلح
 *     حتى القيم الفاسدة المحفوظة مسبقاً عند أول حفظ قادم)
 */

/** محارف غير مرئية تتسرب من النسخ (Bidi controls + Zero-width + Soft hyphen) */
const INVISIBLE_RE = /[\u00AD\u061C\u180E\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u2069\uFEFF\uFFA0]/g

/** شرطات شبيهة بالشرطة العادية — تُطبَّع إلى ASCII hyphen-minus */
const DASH_LIKE_RE = /[\u02D7\u2010-\u2015\u2043\u2212\u2796\uFF0D\uFF0F]/g

/**
 * تنظيف معرّف منصة: إزالة المحارف الخفية + كل المسافات (المعرفات
 * لا تحتوي مسافات أصلاً) + تطبيع الشرطات الشبيهة + trim.
 * آمنة على أي معرف: G-XXXXXXXXXX / AW-123456789 / GTM-XXXXXXX /
 * Pixel IDs الرقمية / CXXXXXXXXXXXXXXXXXXX (TikTok) / أكواد Test.
 */
export function sanitizeId(v: string): string {
  return v
    .replace(INVISIBLE_RE, '')
    .replace(DASH_LIKE_RE, '-')
    .replace(/\s+/g, '')
    .trim()
}

/**
 * هل يحتوي النص على محارف خفية/شرطات شبيهة ستتأثر بالتنظيف؟
 * تُستخدم لعرض تنبيه لطيف للمستخدم عند اللصق ("تم تنظيف المعرف تلقائياً").
 */
export function needsSanitize(v: string): boolean {
  return sanitizeId(v) !== v
}
